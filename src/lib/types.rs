//! 競技プログラミングでよく使う型の短い別名です。

/// `bool` の短い別名です。
pub type B = bool;
/// `char` の短い別名です。
pub type C = char;
/// `f32` の短い別名です。
pub type F = f32;
/// `isize` の短い別名です。
pub type I = isize;
/// [`String`] の短い別名です。
pub type S = String;
/// `usize` の短い別名です。
pub type U = usize;
/// [`Vec<T>`] の短い別名です。
pub type V<T> = Vec<T>;
